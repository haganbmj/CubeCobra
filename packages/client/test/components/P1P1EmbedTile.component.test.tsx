import React from 'react';

import { render, screen } from '@testing-library/react';

import '@testing-library/jest-dom';

import Card from '@utils/datatypes/Card';
import { P1P1Pack, P1P1VoteSummary } from '@utils/datatypes/P1P1Pack';

import P1P1Embed from 'components/markdown/P1P1Embed';
import P1P1EmbedTile from 'components/markdown/P1P1EmbedTile';
import useP1P1Pack from 'hooks/useP1P1Pack';

jest.mock('hooks/useP1P1Pack', () => ({ __esModule: true, default: jest.fn() }));

const mockedUseP1P1Pack = useP1P1Pack as jest.Mock;

const PACK_ID = '3e9d3a4e-1f1a-4e7d-9a3b-2d5f6a7c8b9d';

const card = (name: string): Card =>
  ({
    cardID: name,
    details: { name, image_normal: `https://example.com/${name}.jpg` },
  }) as any;

const pack = (overrides: Partial<P1P1Pack> = {}): P1P1Pack =>
  ({
    id: PACK_ID,
    createdBy: 'user-1',
    cubeId: 'cube-1',
    date: 1700000000000,
    votesByUser: {},
    cards: [card('Sol Ring'), card('Mana Crypt')],
    createdByUsername: 'dekkerglen',
    seed: 'seed',
    source: 'random',
    ...overrides,
  }) as P1P1Pack;

const votes = (overrides: Partial<P1P1VoteSummary> = {}): P1P1VoteSummary => ({
  totalVotes: 42,
  results: [],
  ...overrides,
});

const defaultCube = { name: 'Test Cube', shortId: 'test' };

interface RenderTileOverrides {
  pack?: P1P1Pack;
  votes?: P1P1VoteSummary;
  cube?: { name: string; shortId: string };
  caption?: string;
  onExpand?: () => void;
}

const renderTile = (overrides: RenderTileOverrides) =>
  render(
    <P1P1EmbedTile
      pack={overrides.pack ?? pack()}
      votes={overrides.votes ?? votes()}
      cube={overrides.cube ?? defaultCube}
      caption={overrides.caption}
      onExpand={overrides.onExpand ?? jest.fn()}
    />,
  );

interface RenderEmbedOverrides {
  pack?: P1P1Pack | null;
  votes?: P1P1VoteSummary | null;
  cube?: { name: string; shortId: string } | null;
  loading?: boolean;
  error?: string | null;
  caption?: string;
}

const renderEmbed = (overrides: RenderEmbedOverrides) => {
  mockedUseP1P1Pack.mockReturnValue({
    pack: overrides.pack ?? null,
    votes: overrides.votes ?? null,
    cube: overrides.cube ?? null,
    loading: overrides.loading ?? false,
    error: overrides.error ?? null,
    refetch: jest.fn(),
  });
  return render(<P1P1Embed id={PACK_ID} caption={overrides.caption} />);
};

describe('P1P1EmbedTile', () => {
  it('shows the cube name, attribution and vote count', () => {
    renderTile({
      cube: { name: 'Vintage Cube', shortId: 'vintage' },
      pack: pack({ createdByUsername: 'dekkerglen', source: 'custom' }),
      votes: votes({ totalVotes: 148 }),
    });
    expect(screen.getByText('Vintage Cube')).toBeInTheDocument();
    expect(screen.getByText(/Curated by/)).toHaveTextContent('dekkerglen');
    expect(screen.getByText(/148 votes/)).toBeInTheDocument();
  });

  it('says Generated by for a random pack', () => {
    renderTile({ pack: pack({ source: undefined }) });
    expect(screen.getByText(/Generated by/)).toBeInTheDocument();
  });

  it('invites an unvoted reader to make a pick', () => {
    renderTile({ votes: votes({ userVote: undefined }) });
    expect(screen.getByRole('button', { name: /Make your pick/ })).toBeInTheDocument();
  });

  it('shows the reader their own pick once they have voted', () => {
    renderTile({ pack: pack({ cards: [card('Sol Ring'), card('Force of Will')] }), votes: votes({ userVote: 1 }) });
    expect(screen.getByRole('button', { name: /See results/ })).toBeInTheDocument();
    expect(screen.getByText(/You picked Force of Will/)).toBeInTheDocument();
  });

  it('draws no per-card interaction', () => {
    const { container } = renderTile({});
    expect(container.querySelectorAll('[data-testid="p1p1-embed-card"] a')).toHaveLength(0);
    expect(container.querySelectorAll('a')).toHaveLength(0);
  });
});

describe('P1P1Embed states', () => {
  it('renders a skeleton and no tile while loading', () => {
    renderEmbed({ loading: true });
    expect(screen.getByTestId('p1p1-embed-skeleton')).toBeInTheDocument();
    expect(screen.queryByTestId('p1p1-embed-tile')).not.toBeInTheDocument();
  });

  it('renders the token text when the pack cannot be resolved', () => {
    const { container } = renderEmbed({ error: 'P1P1 pack not found' });
    expect(screen.queryByTestId('p1p1-embed-tile')).not.toBeInTheDocument();
    expect(container).toHaveTextContent(`[[p1p1:${PACK_ID}]]`);
  });

  it('reconstructs the token with its caption when unresolvable', () => {
    const { container } = renderEmbed({ error: 'P1P1 pack not found', caption: 'Sol Ring or Force of Will?' });
    expect(container).toHaveTextContent(`[[p1p1:${PACK_ID}|Sol Ring or Force of Will?]]`);
  });

  it('renders the resolved tile once the pack, votes and cube all load', () => {
    renderEmbed({ pack: pack(), votes: votes(), cube: defaultCube });
    expect(screen.getByTestId('p1p1-embed-tile')).toBeInTheDocument();
    expect(screen.queryByTestId('p1p1-embed-skeleton')).not.toBeInTheDocument();
  });
});
